"use client";

import { useCallback, useEffect, useState } from "react";
import { RefreshCw } from "lucide-react";
import { Field, Input } from "./Field";
import { getCaptcha } from "@/lib/api";
import { useI18n } from "@/lib/i18n";

/** Self-hosted captcha field. Reports `{captcha_id, captcha_solution}`
 * upward whenever either changes (`null` until a challenge is loaded). */
export function CaptchaField({
  onChange,
  disabled,
}: {
  onChange: (captcha: { captcha_id: string; captcha_solution: string } | null) => void;
  disabled?: boolean;
}) {
  const { t } = useI18n();
  const [captchaId, setCaptchaId] = useState<string | null>(null);
  const [svg, setSvg] = useState("");
  const [solution, setSolution] = useState("");
  const [loading, setLoading] = useState(true);
  const [failed, setFailed] = useState(false);

  const refresh = useCallback(async () => {
    setLoading(true);
    setFailed(false);
    try {
      const challenge = await getCaptcha();
      setCaptchaId(challenge.captcha_id);
      setSvg(challenge.svg);
      setSolution("");
      onChange({ captcha_id: challenge.captcha_id, captcha_solution: "" });
    } catch {
      setFailed(true);
    } finally {
      setLoading(false);
    }
  }, [onChange]);

  useEffect(() => {
    const timer = setTimeout(() => {
      void refresh();
    }, 0);
    return () => clearTimeout(timer);
  }, [refresh]);

  function handleSolution(value: string) {
    setSolution(value);
    if (captchaId) {
      onChange({ captcha_id: captchaId, captcha_solution: value.trim() });
    }
  }

  return (
    <Field label={t("captchaLabel")} required>
      <div className="flex items-stretch gap-2">
        {svg ? (
          <div
            className="flex h-12 min-w-36 flex-1 items-center justify-center overflow-hidden rounded-md border border-ink-200 bg-ink-50"
            aria-label={t("captchaLabel")}
            // SVG is generated by our own backend (no user content).
            dangerouslySetInnerHTML={{ __html: svg }}
          />
        ) : (
          <div className="flex h-12 min-w-36 flex-1 items-center justify-center overflow-hidden rounded-md border border-ink-200 bg-ink-50">
            {!loading && (
              <span className="px-2 text-xs text-ink-400">{t("captchaFailed")}</span>
            )}
          </div>
        )}
        <button
          type="button"
          onClick={() => void refresh()}
          disabled={disabled || loading}
          aria-label={t("captchaRefresh")}
          title={t("captchaRefresh")}
          className="shrink-0 rounded-md border border-ink-200 bg-white px-3 text-ink-600 transition hover:bg-ink-50 disabled:opacity-50"
        >
          <RefreshCw size={16} className={loading ? "animate-spin" : undefined} />
        </button>
      </div>
      {failed && (
        <p className="mt-1 text-xs text-rose-600">{t("captchaFailed")}</p>
      )}
      <div className="mt-2">
        <Input
          placeholder={t("captchaPlaceholder")}
          value={solution}
          onChange={(e) => handleSolution(e.target.value)}
          disabled={disabled || !captchaId}
          autoComplete="off"
          maxLength={10}
        />
      </div>
    </Field>
  );
}
